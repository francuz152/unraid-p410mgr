<?php
/* p410mgr — monitoring: config, SMART, problem detection, MQTT, HA discovery */
require_once __DIR__ . '/lib.php';

const P410_CFG_DIR  = '/boot/config/plugins/p410mgr';
const P410_CFG      = P410_CFG_DIR . '/p410mgr.cfg';
const P410_CRON     = P410_CFG_DIR . '/p410mgr.cron';
const P410_BASELINE = P410_CFG_DIR . '/smart_baseline.json';
const P410_STATE    = '/tmp/p410mgr_state.json';

function p410_cfg_defaults(): array {
  return [
    'MON_ENABLED' => 'no', 'INTERVAL' => '60', 'TEMP_WARN' => '45', 'LANG' => 'auto', 'SKIP_STANDBY' => 'yes', 'IGNORE_CACHE' => 'no', 'IGNORE_BATTERY' => 'no',
    'NOTIFY' => 'yes',
    'MQTT_ENABLED' => 'no', 'MQTT_HOST' => '', 'MQTT_PORT' => '1883', 'MQTT_USER' => '', 'MQTT_PASS' => '',
    'MQTT_TOPIC' => 'unraid/p410', 'MQTT_DISCOVERY' => 'yes', 'MQTT_DISCOVERY_PREFIX' => 'homeassistant',
  ];
}

function p410_cfg_load(): array {
  $cfg = p410_cfg_defaults();
  if (is_readable(P410_CFG)) {
    $ini = @parse_ini_file(P410_CFG, false, INI_SCANNER_RAW) ?: [];
    foreach ($ini as $k => $v) if (array_key_exists($k, $cfg)) $cfg[$k] = $v;
  }
  return $cfg;
}

function p410_cfg_save(array $in): array {
  $cfg = p410_cfg_load();
  foreach (p410_cfg_defaults() as $k => $_) if (isset($in[$k])) $cfg[$k] = str_replace(["\n", "\r", '"'], '', trim((string)$in[$k]));
  $cfg['INTERVAL']  = (string)max(5, min(1440, (int)$cfg['INTERVAL']));
  $cfg['TEMP_WARN'] = (string)max(30, min(70, (int)$cfg['TEMP_WARN']));
  if (!in_array($cfg['LANG'], ['auto', 'en', 'pl'], true)) $cfg['LANG'] = 'auto';
  $cfg['MQTT_PORT'] = (string)max(1, min(65535, (int)$cfg['MQTT_PORT']));
  $cfg['MQTT_TOPIC'] = trim(preg_replace('#[^A-Za-z0-9_/\-]#', '', $cfg['MQTT_TOPIC']), '/') ?: 'unraid/p410';
  $cfg['MQTT_DISCOVERY_PREFIX'] = trim(preg_replace('#[^A-Za-z0-9_/\-]#', '', $cfg['MQTT_DISCOVERY_PREFIX']), '/') ?: 'homeassistant';
  @mkdir(P410_CFG_DIR, 0755, true);
  $txt = '';
  foreach ($cfg as $k => $v) $txt .= $k . '="' . $v . "\"\n";
  file_put_contents(P410_CFG, $txt);
  p410_cron_update($cfg);
  return $cfg;
}

function p410_cron_update(array $cfg): void {
  if ($cfg['MON_ENABLED'] === 'yes') {
    $m = (int)$cfg['INTERVAL'];
    $sched = $m < 60 ? "*/$m * * * *" : ($m % 60 === 0 && $m < 1440 ? '7 */' . ($m / 60) . ' * * *' : '7 3 * * *');
    file_put_contents(P410_CRON, "# Generated by p410mgr\n$sched /usr/bin/php /usr/local/emhttp/plugins/p410mgr/scripts/check.php >/dev/null 2>&1\n");
  } else {
    @unlink(P410_CRON);
  }
  if (is_executable('/usr/local/sbin/update_cron')) exec('/usr/local/sbin/update_cron');
}

/* ---------- SMART ---------- */

function p410_cciss_map(string $slot, string $dev): array {
  $map = [];
  for ($i = 0; $i < 32; $i++) {
    $o = [];
    exec('smartctl -i -d cciss,' . $i . ' ' . escapeshellarg($dev) . ' 2>/dev/null', $o);
    foreach ($o as $line) if (preg_match('/^Serial number:\s*(\S+)/i', $line, $m)) $map[$m[1]] = $i;
  }
  @file_put_contents(P410_CACHE, json_encode([$slot => $map]));
  return $map;
}

function p410_parse_smart(string $txt): array {
  $r = ['health' => null, 'temp' => null, 'defects' => null, 'uncorrected' => null,
        'realloc' => null, 'pending' => null, 'offline_unc' => null, 'hours' => null];
  if (preg_match('/SMART Health Status:\s*(.+)/', $txt, $m)) $r['health'] = trim($m[1]);
  if (preg_match('/overall-health self-assessment test result:\s*(\S+)/', $txt, $m)) $r['health'] = trim($m[1]);
  if (preg_match('/Current Drive Temperature:\s*(\d+)/', $txt, $m)) $r['temp'] = (int)$m[1];
  if (preg_match('/Elements in grown defect list:\s*(\d+)/', $txt, $m)) $r['defects'] = (int)$m[1];
  if (preg_match('/Accumulated power on time, hours:minutes\s*(\d+)/', $txt, $m)) $r['hours'] = (int)$m[1];
  if (preg_match_all('/^(read|write|verify):\s+(?:\S+\s+){5}\S+\s+(\d+)\s*$/m', $txt, $mm)) $r['uncorrected'] = array_sum(array_map('intval', $mm[2]));
  /* ATA */
  $attr = function (string $name) use ($txt) {
    return preg_match('/^\s*\d+\s+' . $name . '\s+.*\s(\d+)(?:\s+\(.*\))?\s*$/m', $txt, $m) ? (int)$m[1] : null;
  };
  $r['realloc']     = $attr('Reallocated_Sector_Ct');
  $r['pending']     = $attr('Current_Pending_Sector');
  $r['offline_unc'] = $attr('Offline_Uncorrectable');
  if ($r['temp'] === null) $r['temp'] = $attr('Temperature_Celsius');
  if ($r['hours'] === null) $r['hours'] = $attr('Power_On_Hours');
  return $r;
}

/* ---------- Full check ---------- */

function p410_check(array $cfg, bool $forceSmart = false): array {
  $st = p410_status();
  $res = ['ts' => date('c'), 'problem' => false, 'problems' => [], 'controllers' => [], 'drives' => []];
  if (isset($st['error'])) { $res['problem'] = true; $res['problems'][] = $st['error']; return $res; }
  $baseline = @json_decode(@file_get_contents(P410_BASELINE) ?: '{}', true) ?: [];
  $prev = @json_decode(@file_get_contents(P410_STATE) ?: '{}', true) ?: [];
  $prevDrives = [];
  foreach ($prev['drives'] ?? [] as $d) $prevDrives[$d['serial'] ?? ''] = $d;
  $baselineChanged = false;
  $tw = (int)$cfg['TEMP_WARN'];

  foreach ($st['controllers'] as $c) {
    $d = $c['detail']; $slot = $c['slot'];
    $ctrl = ['slot' => $slot, 'model' => $c['model'], 'status' => $d['Controller Status'] ?? '?',
             'cache' => $d['Cache Status'] ?? '?', 'battery' => $d['Battery/Capacitor Status'] ?? '—',
             'fw' => $d['Firmware Version'] ?? ''];
    $res['controllers'][] = $ctrl;
    if (strcasecmp($ctrl['status'], 'OK')) $res['problems'][] = p410_t('pr_ctrl', $slot, $ctrl['status']);
    $ctrl['cache_ignored'] = $cfg['IGNORE_CACHE'] === 'yes'; $ctrl['battery_ignored'] = $cfg['IGNORE_BATTERY'] === 'yes';
    if (!$ctrl['cache_ignored'] && strcasecmp($ctrl['cache'], 'OK')) $res['problems'][] = p410_t('pr_cache', $ctrl['cache']);
    if (!$ctrl['battery_ignored'] && $ctrl['battery'] !== '—' && strcasecmp($ctrl['battery'], 'OK')) $res['problems'][] = p410_t('pr_batt', $ctrl['battery']);

    $ldMap = []; $dev = null;
    foreach ($c['lds'] as $l) {
      $ldMap[$l['ld']] = $l;
      if (!$dev && $l['present']) $dev = $l['dev'];
      if (strcasecmp($l['status'], 'OK')) $res['problems'][] = p410_t('pr_ld', $l['ld'], $l['dev'], $l['status']);
    }
    $cmap = [];
    if ($dev) {
      $cached = @json_decode(@file_get_contents(P410_CACHE) ?: '[]', true)[$slot] ?? [];
      $need = array_filter(array_column($c['pds'], 'serial'));
      $cmap = ($cached && !array_diff($need, array_keys($cached))) ? $cached : p410_cciss_map($slot, $dev);
    }

    foreach ($c['pds'] as $p) {
      $ld = $p['lds'] ? ($ldMap[$p['lds'][0]] ?? null) : null;
      $drv = ['bay' => $p['bay'], 'pd' => $p['pd'], 'model' => $p['model'], 'serial' => $p['serial'],
              'size' => $p['size'], 'status' => $p['status'], 'ld' => $ld['ld'] ?? null, 'dev' => $ld['dev'] ?? null,
              'unraid' => $ld['unraid'] ?? ($p['unassigned'] ? 'unassigned' : ''),
              'temp' => is_numeric($p['temp']) ? (int)$p['temp'] : null, 'smart' => null, 'problems' => []];
      $label = p410_t('pr_label', $p['bay'], $p['serial'] . ($drv['unraid'] ? ", {$drv['unraid']}" : ''));
      if (strcasecmp($p['status'], 'OK')) $drv['problems'][] = p410_t('pr_state', $p['status']);

      $n = $cmap[$p['serial']] ?? null;
      if ($n !== null && $dev) {
        $o = []; $rc = 0;
        $standby = $cfg['SKIP_STANDBY'] === 'yes' && !$forceSmart ? ' -n standby' : '';
        exec('smartctl -a' . $standby . ' -d cciss,' . (int)$n . ' ' . escapeshellarg($dev) . ' 2>&1', $o, $rc);
        if (($rc & 0x02) && $standby && preg_match('/STANDBY|SLEEP/i', implode("\n", $o))) {
          $drv['smart'] = $prevDrives[$p['serial']]['smart'] ?? null;
          $drv['standby'] = true;
        } else {
          $drv['smart'] = p410_parse_smart(implode("\n", $o));
        }
      }
      $s = $drv['smart'];
      if ($s) {
        if ($drv['temp'] === null && $s['temp'] !== null) $drv['temp'] = $s['temp'];
        if ($s['health'] !== null && !preg_match('/^(OK|PASSED)$/i', $s['health'])) $drv['problems'][] = "SMART: {$s['health']}";
        if (($s['pending'] ?? 0) > 0) $drv['problems'][] = p410_t('pr_pending', $s['pending']);
        if (($s['offline_unc'] ?? 0) > 0) $drv['problems'][] = p410_t('pr_offline', $s['offline_unc']);
        $b = $baseline[$p['serial']] ?? null;
        if ($b === null) {
          $baseline[$p['serial']] = ['defects' => $s['defects'], 'realloc' => $s['realloc'], 'uncorrected' => $s['uncorrected']];
          $baselineChanged = true;
        } else {
          foreach (['defects' => p410_t('c_defects'), 'realloc' => p410_t('c_realloc'), 'uncorrected' => p410_t('c_uncorr')] as $k => $name) {
            if ($s[$k] !== null && $b[$k] !== null && $s[$k] > $b[$k]) $drv['problems'][] = p410_t('pr_increase', $name, $b[$k], $s[$k]);
          }
        }
      }
      if ($drv['temp'] !== null && $drv['temp'] >= $tw) $drv['problems'][] = p410_t('pr_temp', $drv['temp'], $tw);
      foreach ($drv['problems'] as $pr) $res['problems'][] = "$label: $pr";
      $res['drives'][] = $drv;
    }
  }
  if ($baselineChanged) { @mkdir(P410_CFG_DIR, 0755, true); @file_put_contents(P410_BASELINE, json_encode($baseline)); }
  $res['problem'] = (bool)$res['problems'];
  return $res;
}

function p410_baseline_reset(): void { @unlink(P410_BASELINE); }

/* ---------- MQTT 3.1.1 (QoS 0) ---------- */

function p410_mqtt_str(string $s): string { return pack('n', strlen($s)) . $s; }
function p410_mqtt_len(int $n): string {
  $o = '';
  do { $b = $n % 128; $n = intdiv($n, 128); if ($n > 0) $b |= 0x80; $o .= chr($b); } while ($n > 0);
  return $o;
}

/* $msgs = [[topic, payload, retain], ...] */
function p410_mqtt_publish(array $cfg, array $msgs, ?string &$err = null): bool {
  $sock = @stream_socket_client('tcp://' . $cfg['MQTT_HOST'] . ':' . (int)$cfg['MQTT_PORT'], $eno, $estr, 5);
  if (!$sock) { $err = p410_t('mqtt_conn_fail', $cfg['MQTT_HOST'], $cfg['MQTT_PORT'], $estr); return false; }
  stream_set_timeout($sock, 5);
  $flags = 0x02; $payload = p410_mqtt_str('p410mgr-' . substr(md5(gethostname() . getmypid()), 0, 8));
  if ($cfg['MQTT_USER'] !== '') { $flags |= 0x80; }
  if ($cfg['MQTT_USER'] !== '' && $cfg['MQTT_PASS'] !== '') { $flags |= 0x40; }
  if ($flags & 0x80) $payload .= p410_mqtt_str($cfg['MQTT_USER']);
  if ($flags & 0x40) $payload .= p410_mqtt_str($cfg['MQTT_PASS']);
  $vh = p410_mqtt_str('MQTT') . chr(4) . chr($flags) . pack('n', 30);
  fwrite($sock, chr(0x10) . p410_mqtt_len(strlen($vh . $payload)) . $vh . $payload);
  $ack = fread($sock, 4);
  if (strlen($ack) < 4 || ord($ack[0]) !== 0x20 || ord($ack[3]) !== 0) {
    $codes = [1 => p410_t('mqtt_rc1'), 2 => p410_t('mqtt_rc2'), 3 => p410_t('mqtt_rc3'), 4 => p410_t('mqtt_rc4'), 5 => p410_t('mqtt_rc5')];
    $err = p410_t('mqtt_rejected') . (strlen($ack) >= 4 ? ': ' . ($codes[ord($ack[3])] ?? p410_t('mqtt_rcx', ord($ack[3]))) : p410_t('mqtt_noack'));
    fclose($sock); return false;
  }
  foreach ($msgs as [$topic, $data, $retain]) {
    $body = p410_mqtt_str($topic) . $data;
    fwrite($sock, chr(0x30 | ($retain ? 1 : 0)) . p410_mqtt_len(strlen($body)) . $body);
  }
  fwrite($sock, chr(0xE0) . chr(0));
  fclose($sock);
  return true;
}

/* ---------- MQTT messages + Home Assistant discovery ---------- */

function p410_mqtt_messages(array $cfg, array $res, array $newProblems): array {
  $t = $cfg['MQTT_TOPIC'];
  $j = fn($a) => json_encode($a, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
  $ctrl = $res['controllers'][0] ?? [];
  $temps = array_filter(array_column($res['drives'], 'temp'), fn($x) => $x !== null);
  $state = ['problem' => $res['problem'], 'problems' => $res['problems'], 'problem_count' => count($res['problems']),
            'controller' => $ctrl['status'] ?? null, 'cache' => $ctrl['cache'] ?? null, 'battery' => $ctrl['battery'] ?? null,
            'max_temp' => $temps ? max($temps) : null, 'drives' => count($res['drives']), 'ts' => $res['ts']];
  $msgs = [["$t/state", $j($state), true], ["$t/problem", $res['problem'] ? 'ON' : 'OFF', true]];
  foreach ($res['drives'] as $d) {
    $msgs[] = ["$t/bay/{$d['bay']}", $j([
      'status' => $d['problems'] ? 'PROBLEM' : 'OK', 'problems' => $d['problems'], 'temp' => $d['temp'],
      'model' => $d['model'], 'serial' => $d['serial'], 'unraid' => $d['unraid'], 'dev' => $d['dev'], 'ld' => $d['ld'],
      'hours' => $d['smart']['hours'] ?? null, 'defects' => $d['smart']['defects'] ?? null,
      'realloc' => $d['smart']['realloc'] ?? null, 'pending' => $d['smart']['pending'] ?? null,
      'uncorrected' => $d['smart']['uncorrected'] ?? null, 'health' => $d['smart']['health'] ?? null,
    ]), true];
  }
  if ($newProblems) $msgs[] = ["$t/alert", $j(['ts' => $res['ts'], 'new' => $newProblems, 'all' => $res['problems']]), false];

  if ($cfg['MQTT_DISCOVERY'] === 'yes') {
    $p = $cfg['MQTT_DISCOVERY_PREFIX'];
    $dev = ['identifiers' => ['p410mgr_' . gethostname()], 'name' => 'Smart Array P410 (' . gethostname() . ')',
            'manufacturer' => 'HP', 'model' => $ctrl['model'] ?? 'Smart Array', 'sw_version' => $ctrl['fw'] ?? ''];
    $uid = 'p410mgr_' . preg_replace('/\W/', '_', gethostname());
    $msgs[] = ["$p/binary_sensor/$uid/problem/config", $j(['name' => p410_t('ha_problem'), 'unique_id' => "{$uid}_problem",
      'device_class' => 'problem', 'state_topic' => "$t/state", 'value_template' => "{{ 'ON' if value_json.problem else 'OFF' }}",
      'json_attributes_topic' => "$t/state", 'json_attributes_template' => '{{ {"problems": value_json.problems} | tojson }}',
      'device' => $dev]), true];
    foreach (['controller' => [p410_t('ha_controller'), 'mdi:expansion-card'], 'cache' => [p410_t('ha_cache'), 'mdi:memory'], 'battery' => [p410_t('ha_battery'), 'mdi:battery']] as $k => [$name, $icon]) {
      $msgs[] = ["$p/sensor/$uid/$k/config", $j(['name' => $name, 'unique_id' => "{$uid}_$k", 'icon' => $icon,
        'state_topic' => "$t/state", 'value_template' => "{{ value_json.$k }}", 'device' => $dev]), true];
    }
    $msgs[] = ["$p/sensor/$uid/max_temp/config", $j(['name' => p410_t('ha_maxtemp'), 'unique_id' => "{$uid}_max_temp",
      'device_class' => 'temperature', 'unit_of_measurement' => '°C', 'state_class' => 'measurement',
      'state_topic' => "$t/state", 'value_template' => '{{ value_json.max_temp }}', 'device' => $dev]), true];
    foreach ($res['drives'] as $d) {
      $b = (int)$d['bay'];
      $msgs[] = ["$p/sensor/$uid/bay{$b}_temp/config", $j(['name' => p410_t('ha_bay_temp', $b), 'unique_id' => "{$uid}_bay{$b}_temp",
        'device_class' => 'temperature', 'unit_of_measurement' => '°C', 'state_class' => 'measurement',
        'state_topic' => "$t/bay/$b", 'value_template' => '{{ value_json.temp }}', 'device' => $dev]), true];
      $msgs[] = ["$p/sensor/$uid/bay{$b}_status/config", $j(['name' => p410_t('ha_bay_status', $b), 'unique_id' => "{$uid}_bay{$b}_status",
        'icon' => 'mdi:harddisk', 'state_topic' => "$t/bay/$b", 'value_template' => '{{ value_json.status }}',
        'json_attributes_topic' => "$t/bay/$b", 'device' => $dev]), true];
    }
  }
  return $msgs;
}

/* Full cycle: check, compare with previous run, notify, MQTT */
function p410_run_check(bool $forceSmart = false): array {
  $cfg = p410_cfg_load();
  $prev = @json_decode(@file_get_contents(P410_STATE) ?: '{}', true) ?: [];
  $res = p410_check($cfg, $forceSmart);
  $newProblems = array_values(array_diff($res['problems'], $prev['problems'] ?? []));
  $resolved = array_values(array_diff($prev['problems'] ?? [], $res['problems']));
  $res['new'] = $newProblems; $res['resolved'] = $resolved;

  if ($cfg['NOTIFY'] === 'yes' && is_executable('/usr/local/emhttp/webGui/scripts/notify')) {
    if ($newProblems) exec('/usr/local/emhttp/webGui/scripts/notify -e "Smart Array P410" -s ' . escapeshellarg(p410_t('ntf_problem', count($newProblems)))
      . ' -d ' . escapeshellarg(implode('; ', $newProblems)) . ' -i alert');
    if ($resolved && !$res['problem']) exec('/usr/local/emhttp/webGui/scripts/notify -e "Smart Array P410" -s ' . escapeshellarg(p410_t('ntf_resolved')) . ' -d '
      . escapeshellarg(implode('; ', $resolved)) . ' -i normal');
  }
  $res['mqtt'] = null;
  if ($cfg['MQTT_ENABLED'] === 'yes' && $cfg['MQTT_HOST'] !== '') {
    $err = null;
    $res['mqtt'] = p410_mqtt_publish($cfg, p410_mqtt_messages($cfg, $res, $newProblems), $err) ? 'OK' : $err;
  }
  @file_put_contents(P410_STATE, json_encode($res, JSON_UNESCAPED_UNICODE));
  return $res;
}
